"""
PasswordReset
---------------
Table-only model for the `password_resets` table - see Session's docstring
for why this exists separately from PasswordResetService: a proper schema/
migration home, not an active-record API the service actually uses (the
service's upsert-by-email and constant-time token verification logic stays
in PasswordResetService, talking to this table directly).
"""

from core.database.fields import CharField, DateTimeField, TimestampField
from core.models.BaseModel import BaseModel


class PasswordReset(BaseModel):
    table_name = "password_resets"
    fakeable = False  # real data only - never generated by core/fakedata
    timestamps = False

    email = CharField(max_length=255, primary_key=True)
    token_hash = CharField(max_length=255)
    expires_at = DateTimeField(null=False)
    created_at = TimestampField(auto_now_add=True)
