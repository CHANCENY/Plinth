"""
ApiKey
--------
A long-lived credential a user creates for a program to use - shown once when created and stored only as a
SHA-256 hash, so a database leak doesn't leak working keys (keys are 256-bit random values, so a fast hash is
the right tool; passwords are the thing that needs a slow one).

    pk_3f9c1a7b2d4e.<secret>      <- what the user is given: "<key_id>.<secret>"

key_id is the public part (safe to log, used to look the key up, and as the client_id for OAuth client
credentials and the keyId for signed requests). `scopes` optionally limits the key to some of its owner's
permissions (None = everything the owner can do). Revoking sets revoked_at; the row stays for audit.
"""

import time

from core.database.fields import AutoField, BigIntegerField, CharField, ForeignKey, IntegerField, JSONField, TimestampField
from core.models.BaseModel import BaseModel
from core.models.User import User


class ApiKey(BaseModel):
    table_name = "api_keys"
    fakeable = False  # real data only - never generated by core/fakedata

    id = AutoField()
    uid = IntegerField()
    key_id = CharField(max_length=32, unique=True)
    secret_hash = CharField(max_length=64)
    name = CharField(max_length=100)
    scopes = JSONField(null=True)  # list of permission keys, or NULL for "no restriction"
    expires_at = BigIntegerField(null=True)  # unix seconds
    last_used_at = BigIntegerField(null=True)
    revoked_at = BigIntegerField(null=True)
    created_at = TimestampField(auto_now_add=True)
    updated_at = TimestampField(auto_now_add=True, auto_now=True)
    owner = ForeignKey(column="uid", references=User, on_delete="CASCADE", related_name="api_keys")

    @property
    def is_revoked(self) -> bool:
        return self.revoked_at is not None

    @property
    def is_expired(self) -> bool:
        return self.expires_at is not None and self.expires_at <= int(time.time())

    @property
    def is_usable(self) -> bool:
        return not self.is_revoked and not self.is_expired
