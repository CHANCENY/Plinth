"""
Session
---------
Table-only model for the `sessions` table - holds the schema (declared as
fields below, Django-style - see core/database/fields.py) so this table
follows the same convention as every other model, and can be discovered/run
by the migration CLI (python console.py migration / migrate).

SessionService still owns all the actual session *behavior*
(start/save/regenerate/flash/expiry, etc.) and talks to this table directly
through its own query-builder calls rather than through this model's
inherited find()/save() - a session row's lifecycle (upsert-by-id, expiry
checks, JSON-encoded data) doesn't fit BaseModel's plain insert-or-update
shape. This class exists purely so the schema has a proper home instead of
being embedded inside the service.
"""

from core.database.fields import CharField, DateTimeField, TextField, TimestampField
from core.models.BaseModel import BaseModel


class Session(BaseModel):
    table_name = "sessions"
    fakeable = False  # real data only - never generated by core/fakedata
    timestamps = False  # SessionService manages expires_at itself; created_at/updated_at are DB-side defaults only

    id = CharField(max_length=64, primary_key=True)
    data = TextField()
    expires_at = DateTimeField(null=False)
    created_at = TimestampField(auto_now_add=True)
    updated_at = TimestampField(auto_now_add=True, auto_now=True)
