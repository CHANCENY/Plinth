"""
MediaService
--------------
Everything about turning an upload into a media library item - validation, deciding its type, putting
the file on the public disk (StorageService) and creating the File + Media records - plus replacing a
media item's file and deleting an item with its file.

    media = MediaService(db)
    try:
        item = media.create(uploaded, uid=current_user.uid)     # uploaded: an UploadedFile from request.files
    except MediaUploadError as exc:
        print(exc)                                              # "report.exe: '.exe' files aren't allowed ..."

What gets checked (MediaUploadError carries a message fit to show the user)
    * the upload itself arrived intact and isn't empty
    * size is within MEDIA_MAX_UPLOAD_MB
    * the extension is one of the allowed types below
    * for formats with a recognisable signature (PNG, JPEG, PDF, Office/zip, ...) the content actually
      is that format - a renamed .exe or .html can't pass as .png

What's decided here rather than trusted from the browser
    * the MIME type is looked up from the extension, never taken from the client's Content-Type
    * the display name is the client's filename reduced to its basename with control characters
      removed; the name on disk is generated by StorageService and never contains user input beyond
      a sanitised stem
    * files land on the public disk under media/<YYYY-MM>/

Configuration (.env, all optional)
    MEDIA_MAX_UPLOAD_MB          default 10 - largest single file. (Request bodies are separately capped
                                 by Request.from_handler's max_body_size, 50 MB by default.)
    MEDIA_ALLOWED_EXTENSIONS     default: every extension listed below. Comma-separated; narrows the
                                 list, e.g. "png,jpg,jpeg,webp,pdf". Extensions that aren't in the
                                 built-in list can't be added (there's no media type for them).
"""

import datetime
import re
from pathlib import Path
from typing import Dict, List, Optional, Tuple

from core.models.File import File
from core.models.Media import Media
from core.http.request.UploadedFile import UploadedFile
from core.services.EnvService import EnvService
from core.services.StorageService import StorageService

# extension -> (bundle, MIME type). The single source of truth for what the library accepts.
TYPES: Dict[str, Tuple[str, str]] = {
    "png": ("image", "image/png"),
    "jpg": ("image", "image/jpeg"),
    "jpeg": ("image", "image/jpeg"),
    "gif": ("image", "image/gif"),
    "webp": ("image", "image/webp"),
    "pdf": ("document", "application/pdf"),
    "txt": ("document", "text/plain"),
    "csv": ("document", "text/csv"),
    "doc": ("document", "application/msword"),
    "docx": ("document", "application/vnd.openxmlformats-officedocument.wordprocessingml.document"),
    "xls": ("document", "application/vnd.ms-excel"),
    "xlsx": ("document", "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"),
    "ppt": ("document", "application/vnd.ms-powerpoint"),
    "pptx": ("document", "application/vnd.openxmlformats-officedocument.presentationml.presentation"),
    "odt": ("document", "application/vnd.oasis.opendocument.text"),
    "ods": ("document", "application/vnd.oasis.opendocument.spreadsheet"),
    "odp": ("document", "application/vnd.oasis.opendocument.presentation"),
    "mp3": ("audio", "audio/mpeg"),
    "wav": ("audio", "audio/wav"),
    "ogg": ("audio", "audio/ogg"),
    "m4a": ("audio", "audio/mp4"),
    "mp4": ("video", "video/mp4"),
    "webm": ("video", "video/webm"),
    "mov": ("video", "video/quicktime"),
}

_ZIP = (b"PK\x03\x04",)
_OLE = (b"\xd0\xcf\x11\xe0\xa1\xb1\x1a\xe1",)  # legacy Office (.doc/.xls/.ppt)

# extension -> prefixes the content must start with (formats without a reliable signature are absent)
SIGNATURES: Dict[str, Tuple[bytes, ...]] = {
    "png": (b"\x89PNG\r\n\x1a\n",),
    "jpg": (b"\xff\xd8\xff",),
    "jpeg": (b"\xff\xd8\xff",),
    "gif": (b"GIF87a", b"GIF89a"),
    "pdf": (b"%PDF-",),
    "docx": _ZIP, "xlsx": _ZIP, "pptx": _ZIP, "odt": _ZIP, "ods": _ZIP, "odp": _ZIP,
    "doc": _OLE, "xls": _OLE, "ppt": _OLE,
    "ogg": (b"OggS",),
    "webm": (b"\x1a\x45\xdf\xa3",),
}

_CONTROL_CHARS = re.compile(r"[\x00-\x1f\x7f]")


class MediaUploadError(Exception):
    """An upload that was rejected. The message is safe to show to the person who uploaded it."""


class MediaService:
    def __init__(self, db_connection, env: Optional[EnvService] = None):
        self.db = db_connection
        env = env or EnvService()
        self.storage = StorageService(db_connection, env)
        self.max_bytes = int(env.get_float("MEDIA_MAX_UPLOAD_MB", 10) * 1024 * 1024)

        configured = {e.lower().lstrip(".") for e in env.get_list("MEDIA_ALLOWED_EXTENSIONS")}
        self.allowed: List[str] = [ext for ext in TYPES if not configured or ext in configured]

    # ------------------------------------------------------------------ #
    # what's accepted
    # ------------------------------------------------------------------ #
    @staticmethod
    def bundle_for(filename: str) -> Optional[str]:
        """'image' / 'document' / 'audio' / 'video' for a filename, or None if it isn't a known type."""
        entry = TYPES.get(Path(filename).suffix.lower().lstrip("."))
        return entry[0] if entry else None

    def accept_attribute(self) -> str:
        """For <input type="file" accept="...">, e.g. '.png,.jpg,.pdf'."""
        return ",".join(f".{ext}" for ext in self.allowed)

    @property
    def max_megabytes(self) -> float:
        return self.max_bytes / (1024 * 1024)

    # ------------------------------------------------------------------ #
    # validation
    # ------------------------------------------------------------------ #
    @staticmethod
    def clean_filename(name: str) -> str:
        """The client-supplied filename reduced to a safe display name: basename only, no control chars."""
        name = _CONTROL_CHARS.sub("", name or "")
        name = re.split(r"[\\/]", name)[-1].strip().strip(".")
        if len(name) > 255:
            stem, suffix = Path(name).stem, Path(name).suffix
            name = stem[: 255 - len(suffix)] + suffix
        return name or "file"

    def check(self, uploaded: UploadedFile, clean_name: Optional[str] = None) -> Optional[str]:
        """None if the upload is acceptable, otherwise why not (without the filename prefix)."""
        if not uploaded.is_valid():
            return "the upload didn't arrive intact - please try again"
        content = uploaded.get_content()
        if not content:
            return "the file is empty"
        if len(content) > self.max_bytes:
            return f"the file is larger than the {self.max_megabytes:g} MB limit"

        name = clean_name or self.clean_filename(uploaded.get_client_original_name())
        ext = Path(name).suffix.lower().lstrip(".")
        if ext not in self.allowed:
            shown = f"'.{ext}' files" if ext else "files without an extension"
            return f"{shown} aren't allowed (allowed: {', '.join(self.allowed)})"

        signatures = SIGNATURES.get(ext)
        if signatures and not content.startswith(signatures):
            return f"the content doesn't look like a real .{ext} file"
        if ext == "webp" and not (content[:4] == b"RIFF" and content[8:12] == b"WEBP"):
            return "the content doesn't look like a real .webp file"
        if ext in ("mp4", "m4a") and content[4:8] != b"ftyp":
            return f"the content doesn't look like a real .{ext} file"
        if ext == "wav" and not (content[:4] == b"RIFF" and content[8:12] == b"WAVE"):
            return "the content doesn't look like a real .wav file"
        return None

    # ------------------------------------------------------------------ #
    # create / replace / delete
    # ------------------------------------------------------------------ #
    def create(self, uploaded: UploadedFile, uid=None, name: Optional[str] = None,
               alt: Optional[str] = None, published: bool = True) -> Media:
        """Validates and stores an upload and creates its File + Media records. Raises MediaUploadError."""
        clean = self.clean_filename(uploaded.get_client_original_name())
        error = self.check(uploaded, clean)
        if error:
            raise MediaUploadError(f"{clean}: {error}")

        file_record = self._store(uploaded, clean, uid)
        try:
            media = Media(
                self.db,
                bundle=self.bundle_for(clean),
                name=(name or clean)[:255],
                fid=file_record.fid,
                alt=alt or None,
                uid=uid,
                status=published,
            )
            media.save()
        except Exception:
            self.storage.delete(file_record, hard=True)  # don't leave an orphan behind
            raise
        return media

    def replace_file(self, media: Media, uploaded: UploadedFile, uid=None) -> Media:
        """Swaps the file behind a media item for a new upload of the same type, removing the old one."""
        clean = self.clean_filename(uploaded.get_client_original_name())
        error = self.check(uploaded, clean)
        if error:
            raise MediaUploadError(f"{clean}: {error}")
        if self.bundle_for(clean) != media.bundle:
            raise MediaUploadError(f"{clean}: a {media.bundle} item can only be replaced with another {media.bundle} file")

        old_file = media.file()
        new_file = self._store(uploaded, clean, uid if uid is not None else media.attributes.get("uid"))
        try:
            media.fid = new_file.fid
            media.save()
        except Exception:
            self.storage.delete(new_file, hard=True)
            raise
        if old_file is not None:
            self.storage.delete(old_file)
        return media

    def delete(self, media: Media) -> None:
        """Deletes the media item and its stored file (the File row is soft-deleted, like File.delete())."""
        file_record = media.file()
        media.delete()  # the media row first - it references the file
        if file_record is not None:
            self.storage.delete(file_record)

    # ------------------------------------------------------------------ #
    def url(self, file_record: Optional[File]) -> Optional[str]:
        """Public URL of a file on the public disk, or None."""
        if file_record is None:
            return None
        try:
            return self.storage.url(file_record)
        except ValueError:
            return None

    @staticmethod
    def human_size(size) -> str:
        size = float(size or 0)
        for unit in ("B", "KB", "MB", "GB"):
            if size < 1024 or unit == "GB":
                return f"{size:.0f} {unit}" if unit == "B" else f"{size:.1f} {unit}"
            size /= 1024
        return f"{size:.1f} GB"

    def _store(self, uploaded: UploadedFile, clean_name: str, uid) -> File:
        ext = Path(clean_name).suffix.lower().lstrip(".")
        # A fresh UploadedFile: the sanitised name and the MIME type *we* decided, not the client's
        trusted = UploadedFile(clean_name, uploaded.get_content(), content_type=TYPES[ext][1])
        month = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m")
        return self.storage.store(trusted, uid=uid, disk="public", subdirectory=f"media/{month}")
