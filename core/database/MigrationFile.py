"""
MigrationFile
---------------
Reads and writes the auto-generated files in migrations/ at the project
root. Each file is a plain, importable-by-path Python module (numeric-
prefixed filenames like `0001_create_users_table.py` aren't valid dotted
import names, so these are loaded via importlib.util rather than `import`)
with three module-level values:

    TABLE       str            - the table this migration is for
    FIELDS      Dict[str, str] - every column/constraint's migration_key() -> to_sql(),
                                  as of THIS migration (the full state, not just the diff) -
                                  this is what the next `python console.py migration` run
                                  diffs the model's current fields against
    OPERATIONS  List[str]      - the SQL statements this migration runs, in order
    WARNINGS    List[str]      - anything that needs a human's judgement (see Migrator);
                                  empty for the common case

Migrator (core/database/Migrator.py) is what actually generates/runs these -
this module is just the low-level file format.
"""

import importlib.util
import os
import re
from pathlib import Path
from types import ModuleType
from typing import Dict, List, Optional

FILENAME_RE = re.compile(r"^(\d+)_.+\.py$")

HEADER = '''"""
Auto-generated by `python console.py migration` - do not edit the FIELDS
snapshot by hand (it's what the next run diffs against), but OPERATIONS is
just SQL, so review/adjust it before running `python console.py migrate` if
you need to.
"""

'''


def migrations_dir() -> Path:
    # this file lives at project/core/database/MigrationFile.py
    project_root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
    return Path(project_root) / "migrations"


def list_migration_files() -> List[Path]:
    """Every migration file, in ascending sequence order."""
    directory = migrations_dir()
    if not directory.exists():
        return []
    files = [p for p in directory.glob("*.py") if FILENAME_RE.match(p.name)]
    return sorted(files, key=lambda p: int(FILENAME_RE.match(p.name).group(1)))


def next_sequence_number() -> int:
    files = list_migration_files()
    if not files:
        return 1
    return int(FILENAME_RE.match(files[-1].name).group(1)) + 1


def migration_name(path: Path) -> str:
    """The tracked identifier for a migration file - its filename without the .py extension."""
    return path.stem


def load_migration(path: Path) -> ModuleType:
    spec = importlib.util.spec_from_file_location(path.stem, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def latest_fields_for_table(table: str) -> Optional[Dict[str, str]]:
    """The FIELDS snapshot from the most recent migration file for `table`, or None if there isn't one yet."""
    latest = None
    for path in list_migration_files():
        module = load_migration(path)
        if getattr(module, "TABLE", None) == table:
            latest = module
    return dict(latest.FIELDS) if latest is not None else None


def write_migration_file(
    slug: str,
    table: str,
    fields: Dict[str, str],
    operations: List[str],
    warnings: Optional[List[str]] = None,
) -> Path:
    """slug becomes part of the filename (e.g. "create_users_table", "alter_users_table")."""
    directory = migrations_dir()
    directory.mkdir(parents=True, exist_ok=True)

    sequence = next_sequence_number()
    path = directory / f"{sequence:04d}_{slug}.py"

    lines = [HEADER, f"TABLE = {table!r}\n\n", "FIELDS = {\n"]
    for key, value in fields.items():
        lines.append(f"    {key!r}: {value!r},\n")
    lines.append("}\n\nOPERATIONS = [\n")
    for statement in operations:
        lines.append(f"    {statement!r},\n")
    lines.append("]\n\nWARNINGS = [\n")
    for warning in warnings or []:
        lines.append(f"    {warning!r},\n")
    lines.append("]\n")

    path.write_text("".join(lines), encoding="utf-8")
    return path
