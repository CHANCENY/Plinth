"""
ApiToken
----------
One issued token pair: a short-lived access token and (usually) a long-lived refresh token, created by
the OAuth token endpoint (POST /api/oauth/token). Neither token is stored - only SHA-256 hashes.

    access_hash         hash of an opaque access token; NULL when the access token is a JWT (the JWT carries `jti`)
    refresh_hash        hash of the refresh token; NULL for client-credentials tokens (they have no refresh token)
    family              all tokens descended from one login share it; if an already-used refresh token is ever
                        presented again (it was stolen, or a client is replaying), the whole family is revoked
    api_key_id          the ApiKey this came from, when issued by the client_credentials grant
    scopes              permission keys narrowing the owner's permissions, or NULL for no restriction

Revoking sets revoked_at; the row stays for audit. Times are unix seconds.
"""

import time

from core.database.fields import AutoField, BigIntegerField, CharField, ForeignKey, IntegerField, JSONField, TimestampField
from core.models.BaseModel import BaseModel
from core.models.User import User
from public.apps.apiauth.models.ApiKey import ApiKey


class ApiToken(BaseModel):
    table_name = "api_tokens"
    fakeable = False  # real data only - never generated by core/fakedata

    id = AutoField()
    uid = IntegerField()
    api_key_id = IntegerField(null=True)
    family = CharField(max_length=32)
    jti = CharField(max_length=32, unique=True)
    access_hash = CharField(max_length=64, null=True, unique=True)
    access_expires_at = BigIntegerField()
    refresh_hash = CharField(max_length=64, null=True, unique=True)
    refresh_expires_at = BigIntegerField(null=True)
    scopes = JSONField(null=True)
    last_used_at = BigIntegerField(null=True)
    revoked_at = BigIntegerField(null=True)
    ip = CharField(max_length=45, null=True)
    user_agent = CharField(max_length=255, null=True)
    created_at = TimestampField(auto_now_add=True)
    updated_at = TimestampField(auto_now_add=True, auto_now=True)
    owner = ForeignKey(column="uid", references=User, on_delete="CASCADE", related_name="api_tokens")
    api_key = ForeignKey(column="api_key_id", references=ApiKey, on_delete="CASCADE", related_name="tokens")

    @property
    def is_revoked(self) -> bool:
        return self.revoked_at is not None

    @property
    def access_expired(self) -> bool:
        return self.access_expires_at <= int(time.time())

    @property
    def refresh_expired(self) -> bool:
        return self.refresh_expires_at is None or self.refresh_expires_at <= int(time.time())
